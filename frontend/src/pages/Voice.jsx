import { Mic, Play, RefreshCw, Save, ShieldCheck } from 'lucide-react'
import { useEffect, useState } from 'react'
import { Alert, Badge, Button, Card, CardHeader, Input, Loading, PageHeader, Select, Textarea, Toggle, useToast } from '../components/ui'
import { useAuth } from '../context/AuthContext'
import { get, post, put } from '../lib/api'
import { formatDateTime, useApi } from '../lib/hooks'

export default function Voice() {
  const { canManage } = useAuth()
  const toast = useToast()
  const { data, loading, error, reload } = useApi('/voice/')
  const [form, setForm] = useState(null)
  const [voices, setVoices] = useState(null)
  const [voicesError, setVoicesError] = useState('')
  const [loadingVoices, setLoadingVoices] = useState(false)
  const [saving, setSaving] = useState(false)
  const [testText, setTestText] = useState('Hi! Thanks for your message — we have a couple of slots tomorrow.')
  const [testing, setTesting] = useState(false)
  const [sample, setSample] = useState(null)

  useEffect(() => { if (data) setForm(data.settings) }, [data])

  async function loadVoices() {
    setLoadingVoices(true)
    setVoicesError('')
    try {
      setVoices(await get('/voice/voices/'))
    } catch (err) {
      setVoicesError(err.message)
    } finally {
      setLoadingVoices(false)
    }
  }
  useEffect(() => { if (data?.configured && canManage) loadVoices() }, [data?.configured, canManage])

  if (loading && !form) return <Loading />
  if (error) return <Alert tone="error">{error.message}</Alert>
  if (!form) return null
  const set = (k) => (v) => setForm((f) => ({ ...f, [k]: v?.target ? v.target.value : v }))

  async function save() {
    setSaving(true)
    try {
      const { updated_at, clone_consent_at, is_cloned_voice, ...body } = form
      await put('/voice/', body)
      toast('Voice settings saved.')
      reload(true)
    } catch (err) {
      toast(err.message, 'error')
    } finally {
      setSaving(false)
    }
  }

  async function test() {
    setTesting(true)
    setSample(null)
    try {
      const r = await post('/voice/test/', { text: testText })
      const blob = await fetch(r.media_url, { credentials: 'same-origin' }).then((x) => x.blob())
      setSample({ ...r, src: URL.createObjectURL(blob) })
      reload(true)
    } catch (err) {
      toast(err.message, 'error')
    } finally {
      setTesting(false)
    }
  }

  const cloned = ['cloned', 'professional'].includes(form.voice_category)
  return (
    <div>
      <PageHeader title="Voice notes" description="Optional: reply with natural voice notes generated by ElevenLabs. Text replies work without this."
        actions={<Button icon={Save} onClick={save} loading={saving} disabled={!canManage}>Save</Button>} />
      {!data.configured && (
        <Alert tone="warn" title="ElevenLabs not configured" className="mb-4">Add <code>ELEVENLABS_API_KEY</code> to <code>backend/.env</code> and restart the backend to enable voice notes.</Alert>
      )}
      {data.configured && data.ready_problems.length > 0 && form.enabled && (
        <Alert tone="warn" className="mb-4">{data.ready_problems.join(' ')}</Alert>
      )}
      <div className="grid gap-4 lg:grid-cols-[1fr_360px]">
        <Card>
          <CardHeader title="Voice" icon={Mic} action={<Toggle label="Voice replies" checked={form.enabled} onChange={set('enabled')} disabled={!canManage || !data.configured} />} />
          <div className="space-y-4 p-5">
            <div className="flex items-end gap-2">
              <div className="flex-1">
                <Select label="Voice" value={form.voice_id}
                  onChange={(e) => {
                    const v = voices?.voices.find((x) => x.voice_id === e.target.value)
                    setForm((f) => ({ ...f, voice_id: e.target.value, voice_name: v?.name || '', voice_category: v?.category || '', clone_consent_confirmed: v && ['cloned', 'professional'].includes(v.category) ? false : f.clone_consent_confirmed }))
                  }}
                  options={[{ value: '', label: voices ? 'Select a voice…' : form.voice_name || 'Load voices first' },
                    ...(voices?.voices || []).map((v) => ({ value: v.voice_id, label: `${v.name} · ${v.category}` })),
                    ...(form.voice_id && !voices?.voices.some((v) => v.voice_id === form.voice_id) ? [{ value: form.voice_id, label: form.voice_name || form.voice_id }] : [])]} />
              </div>
              <Button variant="secondary" icon={RefreshCw} loading={loadingVoices} onClick={loadVoices} disabled={!data.configured}>Load voices</Button>
            </div>
            {voicesError && <Alert tone="error">{voicesError}</Alert>}
            {cloned && (
              <div className="rounded-xl border border-amber-200 bg-amber-50 p-4">
                <p className="flex items-center gap-2 text-sm font-medium text-amber-900"><ShieldCheck className="size-4" /> Cloned voice — consent required</p>
                <p className="mt-1 text-xs text-amber-900/80">Only use a cloned voice if the person whose voice it is has given explicit permission, and follow ElevenLabs' voice-cloning terms.</p>
                <label className="mt-3 flex items-start gap-2 text-sm">
                  <input type="checkbox" className="mt-0.5 accent-brand-600" checked={form.clone_consent_confirmed} onChange={(e) => set('clone_consent_confirmed')(e.target.checked)} />
                  I confirm I have the voice owner's consent to use this voice for customer replies.
                </label>
                {data.settings.clone_consent_at && <p className="mt-2 text-xs text-amber-900/70">Consent recorded {formatDateTime(data.settings.clone_consent_at)}</p>}
              </div>
            )}
            <div className="grid gap-4 sm:grid-cols-2">
              <Input label="Model" value={form.model_id} onChange={set('model_id')} hint="ElevenLabs model id, e.g. eleven_multilingual_v2" />
              <Input label="Language code (optional)" value={form.language_code} onChange={set('language_code')} hint="ISO 639-1, e.g. en, es" maxLength={8} />
              <Input label="Stability" type="number" step="0.05" min="0" max="1" value={form.stability} onChange={(e) => set('stability')(Number(e.target.value))} />
              <Input label="Similarity boost" type="number" step="0.05" min="0" max="1" value={form.similarity_boost} onChange={(e) => set('similarity_boost')(Number(e.target.value))} />
            </div>
            <Textarea label="Pronunciation notes" rows={2} value={form.pronunciation_notes} onChange={set('pronunciation_notes')} hint="For your team's reference (e.g. how to say the business name)." />
            <p className="text-xs text-stone-500">Output format: <code>{data.output_format}</code>. WhatsApp shows native voice notes only for OGG/Opus; other formats are sent as regular audio.</p>
          </div>
        </Card>
        <div className="space-y-4">
          <Card>
            <CardHeader title="Test voice" />
            <div className="space-y-3 p-5">
              <Textarea rows={3} value={testText} onChange={(e) => setTestText(e.target.value)} />
              <Button icon={Play} onClick={test} loading={testing} disabled={!data.configured || !data.settings.voice_id} className="w-full">Generate sample</Button>
              {!data.settings.voice_id && data.configured && <p className="text-xs text-stone-500">Select and save a voice first.</p>}
              {sample && (
                <div className="space-y-2">
                  <audio controls src={sample.src} className="w-full" />
                  <div className="flex gap-1">
                    <Badge color={sample.voice_note_compatible ? 'green' : 'amber'}>{sample.voice_note_compatible ? 'Voice-note compatible' : 'Regular audio'}</Badge>
                    <Badge>{Math.round(sample.size / 1024)} KB</Badge>
                  </div>
                </div>
              )}
            </div>
          </Card>
          <Card>
            <CardHeader title="Usage (30 days)" />
            <div className="space-y-2 p-5 text-sm">
              <p className="flex justify-between"><span className="text-stone-500">Generated</span><b>{data.usage_30d.total || 0}</b></p>
              <p className="flex justify-between"><span className="text-stone-500">Characters</span><b>{data.usage_30d.characters || 0}</b></p>
              <p className="flex justify-between"><span className="text-stone-500">Failed</span><b className={data.usage_30d.failed ? 'text-red-600' : ''}>{data.usage_30d.failed || 0}</b></p>
              {voices?.subscription && (
                <p className="flex justify-between border-t border-line pt-2"><span className="text-stone-500">ElevenLabs quota</span><b>{voices.subscription.character_count} / {voices.subscription.character_limit}</b></p>
              )}
              <ul className="space-y-1 border-t border-line pt-2">
                {data.recent.map((r) => (
                  <li key={r.id} className="flex justify-between text-xs">
                    <span className={r.status === 'failed' ? 'text-red-600' : ''}>{r.status}{r.error ? `: ${r.error.slice(0, 60)}` : ''}</span>
                    <span className="text-stone-400">{formatDateTime(r.created_at)}</span>
                  </li>
                ))}
              </ul>
            </div>
          </Card>
        </div>
      </div>
    </div>
  )
}
